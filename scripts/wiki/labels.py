EN = dict(line.split('|', 1) for line in PAIRS.splitlines())
TOWNS = {'Замок':'Castle','Оплот':'Rampart','Башня':'Tower','Инферно':'Inferno','Некрополь':'Necropolis','Темница':'Dungeon','Цитадель':'Stronghold','Крепость':'Fortress','Слияние':'Conflux'}
EN.update(TOWNS)
for town, english in TOWNS.items():
    for prefix, translated in [('Герои','Heroes'),('Существа','Creatures')]:
        # Russian town names use the genitive in these headings.
        genitive = {'Замок':'замка','Оплот':'оплота','Башня':'башни','Инферно':'инферно','Некрополь':'некрополя','Темница':'темницы','Цитадель':'цитадели','Крепость':'крепости','Слияние':'слияния'}[town]
        EN[prefix+' '+genitive] = english+' '+translated.lower()
        EN[prefix+' '+genitive.capitalize()] = english+' '+translated.lower()
ALIASES = {'Кровь  дракона':'Кровь дракона','Убийца дракона':'Убийца драконов','Освобождние':'Освобождение','Подземелья и дяьволы':'Подземелья и дьяволы','Рейнджр':'Рейнджер','Окно просмтора инф. о герое':'Окно просмотра инф. о герое',"Меню 'Игровые действия":"Меню 'Игровые действия'",'Руби и Кромсай(**)':'Руби и кромсай'}
for alias, target in ALIASES.items(): EN[alias] = EN[target]
EN['Замок (см. прим. #4)'] = 'Castle (note #4)'
EN['Клинок Армагеддона (см. прим. #3)'] = "Armageddon's Blade (note #3)"
EN['Отголоски войны (*)'] = 'Spoils of War (*)'
EN['Исп. только в камп. RoE и AB'] = 'RoE and AB campaigns only'
EN['Исп. только в камп. RoE/AB'] = 'RoE/AB campaigns only'


def label(title):
    if title not in EN:
        raise ValueError('Missing reviewed English label: '+title)
    import re
    clean=lambda text:re.sub(r'^\$[0-9A-Fa-f]{2}\s*[—-]\s*','',text)
    return {'ru':clean(title), 'en':clean(EN[title])}
